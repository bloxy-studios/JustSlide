#!/usr/bin/env python3
"""Builds docs/figma-manifest.json + the tables in docs/figma-inventory.md from
design/figma/nodes-1-6_30-52_35-13.json (Figma REST GET /v1/files/:key/nodes,
fetched via the Composio Figma connector) and design/figma/asset-export-map.json."""
import json, datetime
from pathlib import Path
R = Path(__file__).resolve().parents[1]
d = json.loads((R / "design/figma/nodes-1-6_30-52_35-13.json").read_text())
amap = json.loads((R / "design/figma/asset-export-map.json").read_text())["map"]
KEY = "nw47hqMLTtmBMksJ4BnJKb"
def hexc(p):
    c = p["color"]; a = p.get("opacity", 1) * c.get("a", 1)
    return "#%02X%02X%02X" % tuple(round(c[k] * 255) for k in "rgb") + ("" if a > 0.999 else f"@{a:.2f}")
def node(n, ox, oy, depth):
    bb = n.get("absoluteBoundingBox") or {}
    o = {"id": n["id"], "name": n["name"], "type": n["type"], "visible": n.get("visible", True),
         "box": [round(bb.get("x", 0) - ox, 1), round(bb.get("y", 0) - oy, 1), round(bb.get("width", 0), 1), round(bb.get("height", 0), 1)]}
    f = [hexc(p) for p in n.get("fills", []) if p.get("type") == "SOLID" and p.get("visible", True)]
    if f: o["fills"] = f
    s = [hexc(p) for p in n.get("strokes", []) if p.get("type") == "SOLID"]
    if s: o["strokes"] = s; o["strokeWeight"] = n.get("strokeWeight"); o["strokeAlign"] = n.get("strokeAlign")
    if n.get("strokeDashes"): o["strokeDashes"] = n["strokeDashes"]
    for k in ("cornerRadius", "itemSpacing", "layoutMode", "opacity"):
        if n.get(k) not in (None, "NONE", 1) and not (k == "itemSpacing" and n.get("layoutMode") in (None, "NONE")): o[k] = n[k]
    if n.get("layoutMode") not in (None, "NONE"): o["padding"] = [n.get("paddingTop", 0), n.get("paddingRight", 0), n.get("paddingBottom", 0), n.get("paddingLeft", 0)]
    if n["type"] == "TEXT":
        st = n.get("style", {}); o["text"] = n.get("characters"); o["font"] = {"family": st.get("fontFamily"), "weight": st.get("fontWeight"), "size": st.get("fontSize"), "lineHeight": st.get("lineHeightPx"), "letterSpacing": st.get("letterSpacing"), "textCase": st.get("textCase")}
    if n["id"] in amap: o["asset"] = f"assets/icons/{amap[n['id']]}.svg"
    if n.get("componentId"): o["componentId"] = n["componentId"]
    kids = n.get("children", [])
    if kids and depth < 7 and not all(k["type"] in ("VECTOR", "BOOLEAN_OPERATION", "ELLIPSE", "LINE", "GROUP") for k in kids) or n["type"] in ("FRAME", "INSTANCE", "COMPONENT", "COMPONENT_SET") and depth < 7:
        ch = [node(k, ox, oy, depth + 1) for k in kids if k["type"] not in ("VECTOR", "BOOLEAN_OPERATION")]
        if ch: o["children"] = ch
    return o
frames = {}
for fid, v in d["nodes"].items():
    doc = v["document"]; bb = doc["absoluteBoundingBox"]
    frames[fid] = {"name": doc["name"], "size": [bb["width"], bb["height"]], "url": f"https://www.figma.com/design/{KEY}/Slide?node-id={fid.replace(':','-')}",
                   "reference": {"1x": f"design/figma/renders/{fid.replace(':','-')}@1x.png", "2x": f"design/figma/renders/{fid.replace(':','-')}@2x.png"},
                   "components": {k: {"name": c.get("name"), "description": c.get("description")} for k, c in {**v.get("components", {}), **v.get("componentSets", {})}.items()},
                   "tree": node(doc, bb["x"], bb["y"], 0)}
out = {"$comment": "Generated by scripts/gen-figma-manifest.py from the Figma REST node tree. Source of truth for geometry/assets; see docs/figma-inventory.md.",
       "fileKey": KEY, "fileName": d["name"], "fileVersion": d["version"], "lastModified": d["lastModified"], "fetchedVia": "Composio Figma connector (FIGMA_GET_FILE_NODES, FIGMA_RENDER_IMAGES_OF_FILE_NODES)",
       "fetchedAt": "2026-11-13T05:31Z", "frames": frames,
       "assets": [{"nodeId": k, "path": f"assets/icons/{v}.svg", "kind": v.split('/')[0]} for k, v in amap.items()],
       "imageFills": {"count": 4, "usedByRequiredNodes": False, "note": "Image fills exist elsewhere in the file; none are referenced by 1:6, 30:52 or 35:13."}}
(R / "docs/figma-manifest.json").write_text(json.dumps(out, indent=1) + "\n")
print("frames", list(frames), "assets", len(out["assets"]))
