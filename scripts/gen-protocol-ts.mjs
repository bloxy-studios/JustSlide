#!/usr/bin/env node
// Generates apps/browser-chrome/src/generated/protocol.ts from the canonical
// registry (crates/justslide-protocol/registry/justslide.protocol.v1.json).
// `--check` fails when the checked-in file is stale (drift check).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(readFileSync(resolve(root, 'crates/justslide-protocol/registry/justslide.protocol.v1.json'), 'utf8'));
const out = resolve(root, 'apps/browser-chrome/src/generated/protocol.ts');
const defs = reg.definitions;

function ts(s, depth = 0) {
  if (!s || depth > 12) return 'unknown';
  if (s.$ref) return ts(defs[s.$ref.replace('#/definitions/', '')], depth + 1);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(' | ');
  switch (s.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `Array<${ts(s.items, depth + 1)}>`;
    case 'object': {
      const props = s.properties || {};
      const req = new Set(s.required || []);
      const keys = Object.keys(props);
      if (!keys.length) return 'Record<string, never>';
      return '{ ' + keys.map((k) => `${k}${req.has(k) ? '' : '?'}: ${ts(props[k], depth + 1)}`).join('; ') + ' }';
    }
    default: return 'unknown';
  }
}

const ui = reg.commands.filter((c) => (c.exposure || ['ui']).includes('ui'));
let src = `// GENERATED by scripts/gen-protocol-ts.mjs from the protocol registry. Do not edit.\n`;
src += `export const PROTOCOL_VERSION = ${JSON.stringify(reg.version)};\n\n`;
src += `export type UiCommand =\n${ui.map((c) => `  | ${JSON.stringify(c.name)}`).join('\n')};\n\n`;
src += `export interface UiCommandArgs {\n${ui.map((c) => `  ${JSON.stringify(c.name)}: ${ts(c.arguments)};`).join('\n')}\n}\n\n`;
src += `export const AGENT_COMMANDS = ${JSON.stringify(reg.commands.filter((c) => (c.exposure || []).includes('mcp')).map((c) => c.name))} as const;\n`;
src += `export type ErrorCode = ${defs.Error.properties.code.enum.map((e) => JSON.stringify(e)).join(' | ')};\n`;

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch {}
  if (cur !== src) { console.error('protocol.ts is stale: run `bun run protocol:gen`'); process.exit(1); }
  console.log('protocol.ts up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, src);
  console.log(`wrote ${out} (${ui.length} UI commands)`);
}
